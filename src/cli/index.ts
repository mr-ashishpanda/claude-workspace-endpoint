#!/usr/bin/env node
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { spawn } from "node:child_process";
import { fileURLToPath } from "node:url";
import { runBridge } from "../bridge.js";
import { configEnvPath, loadEnv } from "../config/env.js";
import { platformDirs } from "../config/platform.js";
import { MissingCredentialsError, loadCredentials } from "../config/credentials.js";
import { MappingStore, MappingValidationError } from "../config/mappings.js";
import { resolveHome } from "../config/paths.js";
import { SESSION_SCOPES, TRIGGER_MODES, CLAUDE_MODELS } from "../config/types.js";
import { readRunningPid } from "../daemon/pidfile.js";
import { waitForReady } from "../daemon/wait-for-ready.js";
import { checkChannelAccess } from "../slack/channel-check.js";
import { Prompter } from "./prompt.js";
import { runLogs } from "./logs.js";

const SKIP_PERMISSIONS_WARNING =
  "Skip permission prompts (--dangerously-skip-permissions)?\n" +
  "  WARNING: Claude will act without asking. Only for trusted workspaces.";

const SLACK_PREFIX_PROMPT =
  'Tag messages to Claude with the Slack sender, e.g. "[Slack: Jane Doe (U012ABCDEF)] ..."?';

function usage(): void {
  process.stdout.write(
    [
      "slack-claude — local-first Slack ↔ Claude Code bridge",
      "",
      "Usage:",
      "  slack-claude init                 Configure Slack credentials + storage",
      "  slack-claude run                  Start the bridge in the background (alias: start)",
      "  slack-claude stop                 Stop the background bridge",
      "  slack-claude logs [-f]            Show the bridge log (-f to follow)",
      "  slack-claude map add              Add a channel→workspace mapping",
      "  slack-claude map list             List configured mappings",
      "  slack-claude map edit <identity>  Edit an existing mapping",
      "  slack-claude map remove <identity> Remove a mapping",
      "",
    ].join("\n") + "\n",
  );
}

async function cmdInit(): Promise<void> {
  const p = new Prompter();
  try {
    const envPath = configEnvPath();
    const dirs = platformDirs();
    process.stdout.write(
      `Configuring the Slack-Claude bridge. Credentials are written to\n  ${envPath}\n` +
        "(a per-user config file, readable only by you — never commit it).\n",
    );
    if (existsSync(envPath)) {
      const overwrite = await p.confirm("Config already exists — overwrite it?");
      if (!overwrite) {
        process.stdout.write("Aborted; existing config left unchanged.\n");
        return;
      }
    }
    const botToken = await p.ask("Slack bot token (xoxb-…)");
    const appToken = await p.ask("Slack app-level token (xapp-…)");
    const signingSecret = await p.ask("Slack signing secret");
    const home = await p.ask("Local storage location", dirs.data);
    const claudeCli = await p.ask("Claude Code CLI binary", "claude");

    const env = [
      "# Generated by `slack-claude init`. Holds secrets — never commit this file.",
      `SLACK_BOT_TOKEN=${botToken}`,
      `SLACK_APP_TOKEN=${appToken}`,
      `SLACK_SIGNING_SECRET=${signingSecret}`,
      `SLACK_CLAUDE_HOME=${home}`,
      `CLAUDE_CLI_BIN=${claudeCli}`,
      "LOG_LEVEL=info",
      "",
    ].join("\n");
    mkdirSync(dirname(envPath), { recursive: true });
    writeFileSync(envPath, env, { mode: 0o600 });
    process.stdout.write(
      `Wrote ${envPath}. Storage will live under ${resolve(home)}.\n` +
        "Next: `slack-claude map add`, then `slack-claude run`.\n",
    );
  } finally {
    p.close();
  }
}

/** Bot token for live channel checks, or null when credentials aren't configured yet. */
function tryLoadBotToken(): string | null {
  try {
    return loadCredentials().botToken;
  } catch (err) {
    if (err instanceof MissingCredentialsError) return null;
    throw err;
  }
}

/**
 * Prompt for a Slack channel id and, when credentials are available, verify
 * the bot can actually see it before accepting the answer — looping on
 * failure so a typo'd/wrong/un-invited channel is caught immediately instead
 * of silently dropping every future Slack event for that mapping.
 */
async function promptChannel(
  p: Prompter,
  botToken: string | null,
  fallback?: string,
): Promise<string> {
  for (;;) {
    const channel = await p.ask("Slack channel id (e.g. C0123ABCD)", fallback);
    if (!botToken) return channel;
    const result = await checkChannelAccess(botToken, channel);
    if (result.ok) return channel;
    process.stdout.write(
      `  ✗ Channel check failed: ${result.error}\n  Fix the channel id and try again.\n`,
    );
  }
}

async function cmdMapAdd(): Promise<void> {
  const store = MappingStore.load(resolveHome());
  const botToken = tryLoadBotToken();
  if (!botToken) {
    process.stdout.write(
      "  (Skipping live channel validation — Slack credentials not configured; run `slack-claude init`.)\n",
    );
  }
  const p = new Prompter();
  try {
    const identity = await p.ask("Identity (e.g. auth-investigator)");
    const channel = await promptChannel(p, botToken);
    const workspace = await p.ask("Workspace directory (absolute path)");
    const scope = await p.choose("Session scope", SESSION_SCOPES, "channel");
    const trigger = await p.choose("Trigger mode", TRIGGER_MODES, "mention");
    const model = await p.choose("Model family (default = latest, auto)", CLAUDE_MODELS, "default");
    const skipPermissions = await p.confirm(SKIP_PERMISSIONS_WARNING);
    const claudeConfigDir = await p.ask("Custom CLAUDE_CONFIG_DIR (blank = bridge default)");
    const slackPrefix = await p.confirm(SLACK_PREFIX_PROMPT);
    const mapping = store.add({
      identity,
      channel,
      workspace,
      scope,
      trigger,
      model,
      skipPermissions,
      claudeConfigDir,
      slackPrefix,
    });
    process.stdout.write(
      `Added mapping [${mapping.identity}] → ${mapping.workspace} ` +
        `(${mapping.scope}/${mapping.trigger}, model=${mapping.model}` +
        `${mapping.skipPermissions ? ", skip-permissions" : ""}` +
        `${mapping.slackPrefix ? ", slack-prefix" : ""}).\n`,
    );
  } finally {
    p.close();
  }
}

function cmdMapList(): void {
  const store = MappingStore.load(resolveHome());
  const mappings = store.list();
  if (mappings.length === 0) {
    process.stdout.write("No mappings configured. Add one with `slack-claude map add`.\n");
    return;
  }
  for (const m of mappings) {
    process.stdout.write(
      `[${m.identity}]\n` +
        `  channel:     ${m.channel}\n` +
        `  workspace:   ${m.workspace}\n` +
        `  scope:       ${m.scope}\n` +
        `  trigger:     ${m.trigger}\n` +
        `  model:       ${m.model}\n` +
        `  permissions: ${m.skipPermissions ? "skipped (dangerous)" : "enforced"}\n` +
        `  slack tag:   ${m.slackPrefix ? "enabled" : "disabled"}\n` +
        `  config dir:  ${m.claudeConfigDir ?? "(bridge default)"}\n`,
    );
  }
}

async function cmdMapEdit(identity: string): Promise<void> {
  const store = MappingStore.load(resolveHome());
  const current = store.get(identity);
  if (!current) {
    process.stderr.write(`No mapping with identity "${identity}".\n`);
    process.exitCode = 1;
    return;
  }
  const botToken = tryLoadBotToken();
  if (!botToken) {
    process.stdout.write(
      "  (Skipping live channel validation — Slack credentials not configured; run `slack-claude init`.)\n",
    );
  }
  const p = new Prompter();
  try {
    const channel = await promptChannel(p, botToken, current.channel);
    const workspace = await p.ask("Workspace directory", current.workspace);
    const scope = await p.choose("Session scope", SESSION_SCOPES, current.scope);
    const trigger = await p.choose("Trigger mode", TRIGGER_MODES, current.trigger);
    const model = await p.choose(
      "Model family (default = latest, auto)",
      CLAUDE_MODELS,
      current.model,
    );
    const skipPermissions = await p.confirm(SKIP_PERMISSIONS_WARNING, current.skipPermissions);
    const claudeConfigDir = await p.ask(
      "Custom CLAUDE_CONFIG_DIR (blank = bridge default)",
      current.claudeConfigDir,
    );
    const slackPrefix = await p.confirm(SLACK_PREFIX_PROMPT, current.slackPrefix);
    const updated = store.edit(identity, {
      channel,
      workspace,
      scope,
      trigger,
      model,
      skipPermissions,
      claudeConfigDir,
      slackPrefix,
    });
    process.stdout.write(`Updated mapping [${updated.identity}].\n`);
  } finally {
    p.close();
  }
}

async function cmdMapRemove(identity: string): Promise<void> {
  const store = MappingStore.load(resolveHome());
  if (!store.get(identity)) {
    process.stderr.write(`No mapping with identity "${identity}".\n`);
    process.exitCode = 1;
    return;
  }
  const p = new Prompter();
  try {
    const ok = await p.confirm(`Remove mapping "${identity}"?`);
    if (!ok) {
      process.stdout.write("Aborted.\n");
      return;
    }
    store.remove(identity);
    process.stdout.write(`Removed mapping [${identity}].\n`);
  } finally {
    p.close();
  }
}

/**
 * Run inside the detached background child: actually run the bridge and
 * report readiness/failure back to the launching `slack-claude run` over IPC.
 */
async function cmdRunChild(): Promise<void> {
  await runBridge({
    onReady: (pid) => process.send?.({ type: "ready", pid }),
    onFatal: (message) => process.send?.({ type: "error", message }),
  });
}

/**
 * `slack-claude run`: spawn a detached copy of this same CLI in child mode,
 * wait for it to report it's connected to Slack, then exit — the child keeps
 * running independent of this shell (and its terminal) until `slack-claude
 * stop` or a machine reboot.
 */
async function cmdRunDaemon(): Promise<void> {
  const home = resolveHome();
  const existingPid = readRunningPid(home);
  if (existingPid) {
    process.stdout.write(
      `Bridge already running (pid ${existingPid}). Run \`slack-claude stop\` first.\n`,
    );
    return;
  }

  const entry = fileURLToPath(import.meta.url);
  const child = spawn(process.execPath, [entry, "run", "--internal-child"], {
    detached: true,
    stdio: ["ignore", "ignore", "ignore", "ipc"],
  });

  const result = await waitForReady(child);
  if (result.ok) {
    process.stdout.write(
      `Bridge started in the background (pid ${result.pid}).\n` +
        "Use `slack-claude logs -f` to tail output, `slack-claude stop` to stop it.\n",
    );
    child.disconnect();
    child.unref();
  } else {
    process.stderr.write(`Bridge failed to start: ${result.message}\n`);
    process.exitCode = 1;
  }
}

function cmdStop(): void {
  const home = resolveHome();
  const pid = readRunningPid(home);
  if (!pid) {
    process.stdout.write("Bridge is not running.\n");
    return;
  }
  process.kill(pid, "SIGTERM");
  process.stdout.write(`Sent stop signal to bridge (pid ${pid}).\n`);
}

async function main(): Promise<void> {
  const [cmd, sub, arg] = process.argv.slice(2);

  // Populate process.env from the config `.env` (and any project-local `.env`)
  // so every command resolves credentials and storage from the same source.
  loadEnv();

  try {
    if (cmd === "init") {
      await cmdInit();
    } else if (cmd === "run" || cmd === "start") {
      if (sub === "--internal-child") await cmdRunChild();
      else await cmdRunDaemon();
    } else if (cmd === "stop") {
      cmdStop();
    } else if (cmd === "logs") {
      runLogs(sub === "-f" || sub === "--follow");
    } else if (cmd === "map") {
      if (sub === "add") await cmdMapAdd();
      else if (sub === "list") cmdMapList();
      else if (sub === "edit") {
        if (!arg) throw new MappingValidationError("Usage: slack-claude map edit <identity>");
        await cmdMapEdit(arg);
      } else if (sub === "remove") {
        if (!arg) throw new MappingValidationError("Usage: slack-claude map remove <identity>");
        await cmdMapRemove(arg);
      } else {
        usage();
        process.exitCode = 1;
      }
    } else {
      usage();
      if (cmd && cmd !== "help" && cmd !== "--help") process.exitCode = 1;
    }
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    process.stderr.write(`Error: ${message}\n`);
    process.exitCode = 1;
  }
}

void main();

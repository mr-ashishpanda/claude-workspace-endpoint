#!/usr/bin/env node
import "dotenv/config";
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { MappingStore, MappingValidationError } from "../config/mappings.js";
import { resolveHome } from "../config/paths.js";
import { SESSION_SCOPES, TRIGGER_MODES, CLAUDE_MODELS } from "../config/types.js";
import { Prompter } from "./prompt.js";

const SKIP_PERMISSIONS_WARNING =
  "Skip permission prompts (--dangerously-skip-permissions)?\n" +
  "  WARNING: Claude will act without asking. Only for trusted workspaces.";

function usage(): void {
  process.stdout.write(
    [
      "slack-claude — local-first Slack ↔ Claude Code bridge",
      "",
      "Usage:",
      "  slack-claude init                 Configure Slack credentials + storage",
      "  slack-claude map add              Add a channel→workspace mapping",
      "  slack-claude map list             List configured mappings",
      "  slack-claude map edit <identity>  Edit an existing mapping",
      "  slack-claude map remove <identity> Remove a mapping",
      "",
    ].join("\n") + "\n",
  );
}

async function cmdInit(): Promise<void> {
  const p = new Prompter();
  try {
    process.stdout.write(
      "Configuring the Slack-Claude bridge. Credentials are written to .env (gitignored).\n",
    );
    if (existsSync(".env")) {
      const overwrite = await p.confirm(".env already exists — overwrite it?");
      if (!overwrite) {
        process.stdout.write("Aborted; .env left unchanged.\n");
        return;
      }
    }
    const botToken = await p.ask("Slack bot token (xoxb-…)");
    const appToken = await p.ask("Slack app-level token (xapp-…)");
    const signingSecret = await p.ask("Slack signing secret");
    const home = await p.ask("Local storage location", ".slack-claude");
    const claudeCli = await p.ask("Claude Code CLI binary", "claude");

    const env = [
      "# Generated by `slack-claude init`. Never commit this file.",
      `SLACK_BOT_TOKEN=${botToken}`,
      `SLACK_APP_TOKEN=${appToken}`,
      `SLACK_SIGNING_SECRET=${signingSecret}`,
      `SLACK_CLAUDE_HOME=${home}`,
      `CLAUDE_CLI_BIN=${claudeCli}`,
      "LOG_LEVEL=info",
      "LOG_FILE=logs/bridge.log",
      "",
    ].join("\n");
    writeFileSync(".env", env);
    process.stdout.write(
      `Wrote .env. Storage will live under ${resolve(home)}.\n` +
        "Next: `slack-claude map add`, then `npm run dev`.\n",
    );
  } finally {
    p.close();
  }
}

async function cmdMapAdd(): Promise<void> {
  const store = MappingStore.load(resolveHome());
  const p = new Prompter();
  try {
    const identity = await p.ask("Identity (e.g. auth-investigator)");
    const channel = await p.ask("Slack channel id (e.g. C0123ABCD)");
    const workspace = await p.ask("Workspace directory (absolute path)");
    const scope = await p.choose("Session scope", SESSION_SCOPES, "channel");
    const trigger = await p.choose("Trigger mode", TRIGGER_MODES, "mention");
    const model = await p.choose("Model family (default = latest, auto)", CLAUDE_MODELS, "default");
    const skipPermissions = await p.confirm(SKIP_PERMISSIONS_WARNING);
    const mapping = store.add({
      identity,
      channel,
      workspace,
      scope,
      trigger,
      model,
      skipPermissions,
    });
    process.stdout.write(
      `Added mapping [${mapping.identity}] → ${mapping.workspace} ` +
        `(${mapping.scope}/${mapping.trigger}, model=${mapping.model}` +
        `${mapping.skipPermissions ? ", skip-permissions" : ""}).\n`,
    );
  } finally {
    p.close();
  }
}

function cmdMapList(): void {
  const store = MappingStore.load(resolveHome());
  const mappings = store.list();
  if (mappings.length === 0) {
    process.stdout.write("No mappings configured. Add one with `slack-claude map add`.\n");
    return;
  }
  for (const m of mappings) {
    process.stdout.write(
      `[${m.identity}]\n` +
        `  channel:     ${m.channel}\n` +
        `  workspace:   ${m.workspace}\n` +
        `  scope:       ${m.scope}\n` +
        `  trigger:     ${m.trigger}\n` +
        `  model:       ${m.model}\n` +
        `  permissions: ${m.skipPermissions ? "skipped (dangerous)" : "enforced"}\n`,
    );
  }
}

async function cmdMapEdit(identity: string): Promise<void> {
  const store = MappingStore.load(resolveHome());
  const current = store.get(identity);
  if (!current) {
    process.stderr.write(`No mapping with identity "${identity}".\n`);
    process.exitCode = 1;
    return;
  }
  const p = new Prompter();
  try {
    const channel = await p.ask("Slack channel id", current.channel);
    const workspace = await p.ask("Workspace directory", current.workspace);
    const scope = await p.choose("Session scope", SESSION_SCOPES, current.scope);
    const trigger = await p.choose("Trigger mode", TRIGGER_MODES, current.trigger);
    const model = await p.choose(
      "Model family (default = latest, auto)",
      CLAUDE_MODELS,
      current.model,
    );
    const skipPermissions = await p.confirm(SKIP_PERMISSIONS_WARNING, current.skipPermissions);
    const updated = store.edit(identity, {
      channel,
      workspace,
      scope,
      trigger,
      model,
      skipPermissions,
    });
    process.stdout.write(`Updated mapping [${updated.identity}].\n`);
  } finally {
    p.close();
  }
}

async function cmdMapRemove(identity: string): Promise<void> {
  const store = MappingStore.load(resolveHome());
  if (!store.get(identity)) {
    process.stderr.write(`No mapping with identity "${identity}".\n`);
    process.exitCode = 1;
    return;
  }
  const p = new Prompter();
  try {
    const ok = await p.confirm(`Remove mapping "${identity}"?`);
    if (!ok) {
      process.stdout.write("Aborted.\n");
      return;
    }
    store.remove(identity);
    process.stdout.write(`Removed mapping [${identity}].\n`);
  } finally {
    p.close();
  }
}

async function main(): Promise<void> {
  const [cmd, sub, arg] = process.argv.slice(2);

  try {
    if (cmd === "init") {
      await cmdInit();
    } else if (cmd === "map") {
      if (sub === "add") await cmdMapAdd();
      else if (sub === "list") cmdMapList();
      else if (sub === "edit") {
        if (!arg) throw new MappingValidationError("Usage: slack-claude map edit <identity>");
        await cmdMapEdit(arg);
      } else if (sub === "remove") {
        if (!arg) throw new MappingValidationError("Usage: slack-claude map remove <identity>");
        await cmdMapRemove(arg);
      } else {
        usage();
        process.exitCode = 1;
      }
    } else {
      usage();
      if (cmd && cmd !== "help" && cmd !== "--help") process.exitCode = 1;
    }
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    process.stderr.write(`Error: ${message}\n`);
    process.exitCode = 1;
  }
}

void main();
